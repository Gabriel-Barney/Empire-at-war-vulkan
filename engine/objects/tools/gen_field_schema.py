"""Generates engine/objects/src/field_schema_table.inc from docs/re/xml_field_tables.md.

Clean-room: the input is the RE prose/table document only (tag -> parser code -> member offset,
grouped by owning class segment). Re-run after the doc changes:

    python engine/objects/tools/gen_field_schema.py

Each output row: {tag, code, offset, segment owner, table ordinal, sample kind}. Rows keep the
document order, which is also the lookup priority (first matching row wins).
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
SRC = os.path.join(ROOT, "docs", "re", "xml_field_tables.md")
DST = os.path.join(ROOT, "engine", "objects", "src", "field_schema_table.inc")
TAGS = os.path.join(ROOT, "docs", "re", "xml_tags.md")
DST_SUB = os.path.join(ROOT, "engine", "objects", "src", "sub_object_names.inc")
# Section of xml_tags.md that lists the ability / action sub-object element names
# (<Abilities><Combat_Bonus_Ability ...>, <Unit_Abilities_Data><Unit_Ability>, ...).
SUB_SECTION = "## AllyEventClass"
RTTI = os.path.join(ROOT, "docs", "re", "rtti_classes.txt")
DST_BEH = os.path.join(ROOT, "engine", "objects", "src", "behavior_classes.inc")

# Segment-owner corrections: (table address, owner as labelled in the doc) -> owner. The doc's
# generator names a segment after the first class whose XML uses its tags, which mislabels a few
# runs of rows (2026-10-28, S1 open item):
#   * table 0xa39ab0: the three `GameObjectType` runs (Tooltip_Text; Projectile_Damage, Damage_Type,
#     Projectile_Appearance_Delay_Frames; Turret_* / Barrel_Bone_Name) sit between HardPoint runs at
#     HardPoint offsets (strings every 0x20 from 0x120 next to Fire_SFXEvent 0x140 ... Fire_Bone_B
#     0x1a0; 0x478 right after Repair_Amount_Per_Frame 0x474), while GameObjectType's own Text_ID /
#     Projectile_Damage / Damage_Type are 0x120 / 0x474 / 0x418 in table 0xa2bf90 (OBJECT_TYPES.md 5.4).
#     They are HardPoint fields.
#   * table 0xa39ab0, end of the `Faction` segment: Initially_Enabled 0x40 ... Excluded_Unit_Categories
#     0x88 drop from Faction offsets (0x3098) to the 0x3c..0x88 run that continues without a gap into
#     Force_Healing_Ability (Excluded_Unit_Types 0x90, ...): the special-ability base fields every
#     *_Ability sub-object shares. Owner "Ability_Base" (no element of that name exists).
OWNER_FIXES = {
    ("0xa39ab0", "GameObjectType"): "HardPoint",
}
ROW_OWNER_FIXES = {
    ("0xa39ab0", "Faction", tag): "Ability_Base"
    for tag in ("Initially_Enabled", "Activation_Style", "Causes_Despawn", "Terminate_Effect_On_Move_Command",
                "Unit_Strength_Category", "Unit_Strength_Factor", "Applicable_Unit_Categories",
                "Applicable_Unit_Types", "Excluded_Unit_Categories")
}

table_re = re.compile(r"^## Table (0x[0-9a-fA-F]+)")
seg_re = re.compile(r"^### Segment: fields of `([^`]+)` objects")
row_re = re.compile(r"^\|\s*([A-Za-z0-9_\-\.]+)\s*\|\s*(0x[0-9a-fA-F]+)\s*\|\s*(0x[0-9a-fA-F]+)\s*\|\s*([^|]*?)\s*\|\s*$")


def main():
    table = -1
    table_addr = None
    owner = None
    rows = []
    with open(SRC, encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            m = table_re.match(line)
            if m:
                table += 1
                table_addr = m.group(1).lower()
                owner = None
                continue
            m = seg_re.match(line)
            if m:
                owner = OWNER_FIXES.get((table_addr, m.group(1)), m.group(1))
                continue
            if owner is None or table < 0:
                continue
            m = row_re.match(line)
            if not m or m.group(1) == "tag":
                continue
            row_owner = ROW_OWNER_FIXES.get((table_addr, owner, m.group(1)), owner)
            rows.append((m.group(1), int(m.group(2), 16), int(m.group(3), 16), row_owner, table, m.group(4)))
    if not rows:
        print("no rows parsed from", SRC)
        return 1
    with open(DST, "w", encoding="utf-8", newline="\n") as o:
        o.write("// GENERATED by engine/objects/tools/gen_field_schema.py from docs/re/xml_field_tables.md.\n")
        o.write("// Do not edit. %d rows: {tag, parser code, member offset, segment owner, table, sample}.\n" % len(rows))
        for tag, code, off, own, tab, sample in rows:
            o.write('{"%s", 0x%x, 0x%x, "%s", %d, "%s"},\n' % (tag, code, off, own, tab, sample))
    print("wrote", len(rows), "rows to", DST)

    names = []
    with open(TAGS, encoding="utf-8") as f:
        lines = f.read().split("\n")
    for i, line in enumerate(lines):
        if line.startswith(SUB_SECTION):
            for body in lines[i + 1:]:
                if body.startswith("## "):
                    break
                names += re.findall(r"`([A-Za-z0-9_]+)`", body)
            break
    if not names:
        print("no sub-object names found in", TAGS)
        return 1
    with open(DST_SUB, "w", encoding="utf-8", newline="\n") as o:
        o.write("// GENERATED by engine/objects/tools/gen_field_schema.py from docs/re/xml_tags.md (%s).\n" % SUB_SECTION[3:])
        o.write("// Do not edit. %d ability / action sub-object element names.\n" % len(names))
        for n in names:
            o.write('"%s",\n' % n)
    print("wrote", len(names), "names to", DST_SUB)

    # Behavior classes: RTTI classes whose ancestor list contains BehaviorClass (BehaviorClass itself
    # excluded), in file order.
    beh = []
    with open(RTTI, encoding="utf-8") as f:
        for line in f:
            parts = [p.strip() for p in line.split("|")]
            if len(parts) < 4 or parts[0] == "BehaviorClass":
                continue
            ancestors = [a.strip() for a in parts[3].split(",")]
            if "BehaviorClass" in ancestors and re.fullmatch(r"[A-Za-z0-9_]+", parts[0]):
                beh.append(parts[0])
    if not beh:
        print("no behavior classes found in", RTTI)
        return 1
    with open(DST_BEH, "w", encoding="utf-8", newline="\n") as o:
        o.write("// GENERATED by engine/objects/tools/gen_field_schema.py from docs/re/rtti_classes.txt.\n")
        o.write("// Do not edit. %d classes deriving from BehaviorClass, file order.\n" % len(beh))
        for n in beh:
            o.write('"%s",\n' % n)
    print("wrote", len(beh), "behavior classes to", DST_BEH)
    return 0


if __name__ == "__main__":
    sys.exit(main())
