#!/usr/bin/env python3
"""build_reports.py - turn docs/assets/catalog.json into CATALOG.md and produce the
merged (load-order applied) extraction of text/config/shader content.

  build_reports.py catalog-md <catalog.json> <CATALOG.md>
  build_reports.py merge-index <catalog.json> <megindex.json>...
  build_reports.py extract-merged <game> <outroot> <label=file.meg>...   (labels in load order;
        later archives override earlier ones; only TEXT_EXTS are written)

Run with python3 -I. Paths of archives are passed explicitly; nothing is executed from
the data directories.
"""
import collections
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import megtool  # noqa: E402

TEXT_EXTS = {'XML', 'LUA', 'TXT', 'H', 'RC', 'FX', 'FXO', 'FXH', 'TEC', 'MTD'}

# Engine mount order. Base archives follow megafiles.xml; the patch archives are
# mounted afterwards by the executable (they are not listed in megafiles.xml) and
# override base content. 64Patch (Steam 64-bit update) is last.
FOC_ORDER = ['config', 'shaders', 'maps', 'movies', 'models', 'englishspeech', 'textures',
             'music', 'Patch', 'Patch2', '64Patch']
EAW_ORDER = ['models', 'englishspeech', 'music', 'config', 'shaders', 'movies', 'cinematics',
             'textures', 'maps', 'patch', 'patch2', '64Patch']


def ext_of(name):
    leaf = name.replace('/', '\\').rsplit('\\', 1)[-1]
    return leaf.rsplit('.', 1)[-1].upper() if '.' in leaf else '(none)'


def topdir(name):
    parts = name.replace('/', '\\').split('\\')
    if len(parts) == 1:
        return '(bare filename, no directory)'
    return '\\'.join(parts[:2]) if len(parts) > 2 else parts[0]


def human(n):
    for u in ('B', 'KB', 'MB', 'GB'):
        if n < 1024 or u == 'GB':
            return ('%d %s' % (n, u)) if u == 'B' else ('%.1f %s' % (n, u))
        n /= 1024.0


def catalog_md(cat_path, out_path):
    cat = json.load(open(cat_path))
    L = []
    w = L.append
    w('# MEG Asset Catalog (EaW + FoC, Steam 64-bit v1.121)\n')
    w('Generated by `tools/meg/build_reports.py catalog-md` from `catalog.json` '
      '(produced by `megtool.py catalog`). Every archive parsed as **MEG v1**, '
      'unencrypted; every record CRC verified against CRC-32(uppercased name), '
      'record tables are CRC-sorted, payloads are contiguous and end exactly at EOF.\n')

    w('## Archives\n')
    w('| Archive | Format | Entries | Payload | File size | Problems |')
    w('|---|---|---:|---:|---:|---:|')
    tot_e = tot_b = 0
    for k, v in cat.items():
        b = sum(e['size'] for e in v['entries'])
        tot_e += len(v['entries'])
        tot_b += b
        w('| `%s` | v%d%s | %d | %s | %s | %d |' % (
            k, v['version'], ' (encrypted)' if v['encrypted'] else '', len(v['entries']),
            human(b), human(v['file_size']), len(v['problems'])))
    w('| **total** | | **%d** | **%s** | | |\n' % (tot_e, human(tot_b)))

    w('### Not cataloged\n')
    if 'eaw/models' not in cat:
        w('- `eaw/models.meg` (624 MB) exceeds the 400 MB transfer limit. Run '
          '`py tools\\meg\\megindex.py "<GameData>\\Data\\models.meg" eaw/models -o eaw_models_index.json` '
          'on the PC and merge with `build_reports.py merge-index`.')
    w('- Localised speech MEGs listed in megafiles.xml (French/German/...Speech.meg) are '
      'not installed in this copy; the engine silently skips missing entries.\n')

    for game in ('foc', 'eaw'):
        arcs = {k: v for k, v in cat.items() if k.startswith(game + '/')}
        w('## %s: counts by extension\n' % game.upper())
        ex_n = collections.Counter()
        ex_b = collections.Counter()
        for v in arcs.values():
            for e in v['entries']:
                ex_n[ext_of(e['name'])] += 1
                ex_b[ext_of(e['name'])] += e['size']
        w('| Ext | Files | Bytes |')
        w('|---|---:|---:|')
        for x, n in ex_n.most_common():
            w('| %s | %d | %s |' % (x, n, human(ex_b[x])))
        w('')
        w('## %s: counts by top-level directory\n' % game.upper())
        td_n = collections.Counter()
        td_b = collections.Counter()
        for v in arcs.values():
            for e in v['entries']:
                td_n[topdir(e['name'])] += 1
                td_b[topdir(e['name'])] += e['size']
        w('| Directory | Files | Bytes |')
        w('|---|---:|---:|')
        for x, n in sorted(td_n.items()):
            w('| `%s` | %d | %s |' % (x, n, human(td_b[x])))
        w('')

    # Overrides
    for game, order in (('foc', FOC_ORDER), ('eaw', EAW_ORDER)):
        w('## %s: override relationships (load order applied)\n' % game.upper())
        w('Mount order: ' + ' -> '.join('`%s`' % o for o in order) +
          ' (later wins). Only archives present in the catalog are considered.\n')
        owner = {}
        shadows = collections.defaultdict(lambda: collections.Counter())
        examples = collections.defaultdict(list)
        for label in order:
            key = '%s/%s' % (game, label)
            if key not in cat:
                continue
            for e in cat[key]['entries']:
                n = e['name'].upper()
                if n in owner:
                    shadows[(label, owner[n])][ext_of(n)] += 1
                    if len(examples[(label, owner[n])]) < 3:
                        examples[(label, owner[n])].append(n)
                owner[n] = label
        if not shadows:
            w('No shadowing.\n')
        else:
            w('| Overriding archive | Shadows | Files | By ext | Examples |')
            w('|---|---|---:|---|---|')
            for (a, b), c in shadows.items():
                w('| `%s` | `%s` | %d | %s | %s |' % (
                    a, b, sum(c.values()), ', '.join('%s %d' % kv for kv in c.most_common()),
                    '<br>'.join('`%s`' % x for x in examples[(a, b)])))
            w('')
        # files introduced only by patches
        for label in order:
            key = '%s/%s' % (game, label)
            if key in cat and label.lower() in ('patch', 'patch2', '64patch'):
                newf = [e['name'] for e in cat[key]['entries'] if owner[e['name'].upper()] == label]
                base = set()
                for l2 in order:
                    if l2 == label:
                        break
                    k2 = '%s/%s' % (game, l2)
                    if k2 in cat:
                        base.update(e['name'].upper() for e in cat[k2]['entries'])
                added = [n for n in newf if n.upper() not in base]
                w('- `%s` adds %d file(s) not present in earlier archives.' % (label, len(added)))
        w('')

    # EaW vs FoC overlap
    w('## EaW vs FoC asset overlap (FoC shadowing EaW)\n')
    w('Effective file set per game = load-order winner for each name (SFX archives are '
      'their own namespace and included as-is). Assuming FoC mounts EaW `GameData` beneath '
      'its own `Data` (unverified, see below), every name in both sets is served from FoC.\n')
    def effective(game, order):
        own = {}
        for label in order + [k.split('/', 1)[1] for k in cat if k.startswith(game + '/Audio/')]:
            key = '%s/%s' % (game, label)
            if key in cat:
                for e in cat[key]['entries']:
                    own[e['name'].upper()] = (label, e)
        return own
    fo, eo = effective('foc', FOC_ORDER), effective('eaw', EAW_ORDER)
    both = set(fo) & set(eo)
    grp = collections.defaultdict(lambda: [0, 0, 0])
    for n in both:
        fl, fe = fo[n]
        el, ee = eo[n]
        g = grp[(fl, el, ext_of(n))]
        g[0] += 1
        g[1] += fe['size'] == ee['size']
        g[2] += fe['size']
    w('| FoC archive (wins) | EaW archive (shadowed) | Ext | Files | Same size | FoC bytes |')
    w('|---|---|---|---:|---:|---:|')
    for (fl, el, x), (n, same, b) in sorted(grp.items(), key=lambda kv: -kv[1][0]):
        w('| `%s` | `%s` | %s | %d | %d | %s |' % (fl, el, x, n, same, human(b)))
    eaw_only = set(eo) - set(fo)
    xo = collections.Counter(ext_of(n) for n in eaw_only)
    w('\n- Shadowed names: %d. FoC-only names: %d. **EaW-only names (only reachable if FoC '
      'mounts GameData): %d** (%s).' % (len(both), len(set(fo) - set(eo)), len(eaw_only),
                                      ', '.join('%s %d' % kv for kv in xo.most_common())))
    if 'eaw/models' not in cat:
        w('- EaW `models.meg` is not in the catalog yet, so ALO/ALA overlap is incomplete.')
    w('- "Same size" counts entries whose size matches; identical content is not proven '
      '(CRCs are name hashes, not content hashes).\n')

    # Cross-game
    w('## Cross-game: FoC config.meg vs EaW config.meg\n')
    if 'foc/config' in cat and 'eaw/config' in cat:
        f = {e['name'].upper(): e for e in cat['foc/config']['entries']}
        e_ = {e['name'].upper(): e for e in cat['eaw/config']['entries']}
        both = set(f) & set(e_)
        same = sum(1 for n in both if f[n]['size'] == e_[n]['size'])
        w('- Names in both: %d (same size: %d); FoC-only: %d; EaW-only: %d.' % (
            len(both), same, len(set(f) - set(e_)), len(set(e_) - set(f))))
        w('- FoC is expected to also mount the EaW `GameData` archives as a lower-priority '
          'fallback layer (many EaW-era models/textures are absent from FoC MEGs). This is '
          '**not yet verified** from the binary; confirm mount order in the RE stream.\n')

    w('## Extensionless entries\n')
    nox = [(k, e) for k, v in cat.items() for e in v['entries'] if ext_of(e['name']) == '(none)']
    if nox:
        w('| Archive | Name | Size | Offset |')
        w('|---|---|---:|---:|')
        for k, e in nox:
            w('| `%s` | `%s` | %d | %d |' % (k, e['name'], e['size'], e['offset']))
        w('\nThese have no extension; by prefix (`P_`) and size they look like particle-system '
          'ALO files packed without `.ALO`. Lookups for `P_*.ALO` will not hit them, so they are '
          'probably dead data. Loaders should treat them as orphans rather than an error.\n')
    else:
        w('None.\n')

    w('## Notable findings\n')
    w('- `config.meg` `.LUA` files are **compiled Lua 5.0 bytecode** (`\\x1BLuaP`, 32-bit '
      'size_t/int, 8-byte lua_Number). `64Patch.meg` re-ships the **same 324 (FoC) / 260 '
      '(EaW) names as plain-text Lua source** (Perforce `$Id` headers), shadowing the '
      'bytecode. The merged extraction therefore contains Lua *source*.')
    w('- `shaders.meg` contains only compiled `.FXO` effects (D3D9 effect binaries, magic `01 09 FF FE` = fx_2_0); no '
      '`.FX` HLSL source ships in any archive. `Patch2.meg` overrides 3 FXOs.')
    w('- `Audio/SFX/*.meg` store **bare filenames** (no `DATA\\AUDIO\\SFX\\` prefix); the '
      'audio system resolves SFX by leaf name against these archives.')
    w('- All other archive names are stored upper-case with `\\` separators and a `DATA\\` prefix.')
    open(out_path, 'w').write('\n'.join(L) + '\n')


def extract_merged(game, outroot, specs):
    owner = {}
    arcs = {}
    for spec in specs:
        label, path = spec.split('=', 1)
        m = megtool.MegArchive(path)
        arcs[label] = m
        for e in m.entries:
            if ext_of(e.name) in TEXT_EXTS:
                owner.setdefault(e.name.upper(), []).append((label, e))
    index = []
    for name in sorted(owner):
        chain = owner[name]
        label, e = chain[-1]
        p = megtool.safe_out_path(outroot, e.name)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, 'wb') as f:
            f.write(arcs[label].read(e))
        index.append({'name': e.name, 'size': e.size, 'crc': '%08X' % e.crc,
                      'from': label, 'shadows': [l for l, _ in chain[:-1]]})
    json.dump({'game': game, 'load_order': [s.split('=', 1)[0] for s in specs],
               'files': index}, open(os.path.join(outroot, 'INDEX.json'), 'w'), indent=1)
    print('%s: wrote %d files' % (game, len(index)), file=sys.stderr)


if __name__ == '__main__':
    if sys.argv[1] == 'catalog-md':
        catalog_md(sys.argv[2], sys.argv[3])
    elif sys.argv[1] == 'merge-index':  # merge-index <catalog.json> <megindex_out.json>...
        cat = json.load(open(sys.argv[2]))
        for p in sys.argv[3:]:
            cat.update(json.load(open(p)))
        json.dump(cat, open(sys.argv[2], 'w'), indent=1)
    elif sys.argv[1] == 'extract-merged':
        extract_merged(sys.argv[2], sys.argv[3], sys.argv[4:])
    else:
        print(__doc__)
