#!/usr/bin/env python3
"""Extract XML tag names the engine parses and cross-check against vanilla Data/XML.
Usage: xml_tags.py <exe> <code.pkl> <rtti.json> <xml_dir> <out.json> <out.md>
A string is a tag candidate if it is identifier-like and either (a) is used as an element
name in the vanilla XML corpus, or (b) is referenced from a function that references >=5
corpus-confirmed tags (i.e. a parser). Owner = locality class of the referencing function."""
import sys, os, re, json, pickle, collections, glob
import xml.etree.ElementTree as ET
sys.path.insert(0, os.path.dirname(__file__))
from name_fn import Namer
from locality import build_index, nearest

IDENT = re.compile(r'^[A-Za-z_][A-Za-z0-9_]{2,63}$')

def corpus(xml_dir):
    tags = collections.Counter(); per_file_root = collections.Counter(); attrs = collections.Counter()
    for p in glob.glob(os.path.join(xml_dir, '**', '*.[xX][mM][lL]'), recursive=True):
        try:
            raw = open(p, 'rb').read()
            raw = re.sub(rb'<\?xml[^>]*\?>', b'', raw)
            root = ET.fromstring(raw.decode('latin1'))
        except Exception:
            # tolerant fallback: regex
            for m in re.finditer(rb'<([A-Za-z_][A-Za-z0-9_]*)[\s>/]', open(p, 'rb').read()):
                tags[m.group(1).decode()] += 1
            continue
        per_file_root[root.tag] += 1
        for el in root.iter():
            tags[el.tag] += 1
            for a in el.attrib: attrs[a] += 1
    return tags, per_file_root, attrs

def main(exe, pkl, rttij, xml_dir, outj, outmd):
    n = Namer(exe, pkl, rttij); lab, keys = build_index(n)
    tags, roots, attrs = corpus(xml_dir)
    tagset = {t.lower(): t for t in tags}
    S = n.S
    # function -> referenced identifier strings
    fn_ids = collections.defaultdict(set)
    for f, (e, ev) in n.code.items():
        for x in ev:
            if x[0] in ('lea', 'mov') and len(x) == 4 and x[2] in S and S[x[2]]['enc'] == 'a':
                s = S[x[2]]['s']
                if IDENT.match(s): fn_ids[f].add(s)
    parsers = {f for f, ids in fn_ids.items() if sum(1 for s in ids if s.lower() in tagset) >= 5}
    result = {}
    for f, ids in fn_ids.items():
        for s in ids:
            confirmed = s.lower() in tagset
            if not (confirmed or (f in parsers and '_' in s)): continue
            owner = nearest(lab, keys, f, 1)
            e = result.setdefault(s, {'tag': s, 'in_vanilla_xml': confirmed, 'xml_count': tags.get(tagset.get(s.lower(), ''), 0),
                                       'functions': [], 'owners': []})
            e['functions'].append(hex(f))
            if owner: e['owners'].append(owner[0][1])
    for e in result.values():
        e['owner'] = collections.Counter(e['owners']).most_common(1)[0][0] if e['owners'] else '?'
        del e['owners']
    unparsed = sorted(t for t in tags if t not in result and t.lower() not in {k.lower() for k in result})
    json.dump({'tags': sorted(result.values(), key=lambda e: (e['owner'], e['tag'])),
               'xml_root_elements': roots.most_common(), 'xml_attributes': attrs.most_common(),
               'vanilla_tags_not_found_in_exe_xrefs': unparsed}, open(outj, 'w'), indent=1)
    by = collections.defaultdict(list)
    for e in result.values(): by[e['owner']].append(e)
    with open(outmd, 'w') as fo:
        fo.write('# XML tags parsed by StarWarsG.exe (FoC x64)\n\n')
        fo.write(f'Generated by `tools/re/xml_tags.py`. {len(result)} tag strings referenced from code; '
                 f'{sum(1 for e in result.values() if e["in_vanilla_xml"])} confirmed in vanilla FoC Data/XML '
                 f'({len(tags)} distinct element names in corpus). Owner = class attributed by address locality of the '
                 'referencing function (approximate: one parser TU per class). `*` = not used by vanilla XML (mod-available / legacy).\n\n')
        fo.write('## Root elements in vanilla XML (file type -> count)\n\n')
        fo.write(', '.join(f'`{r}` ({c})' for r, c in roots.most_common(60)) + '\n\n')
        for owner in sorted(by, key=lambda o: -len(by[o])):
            es = sorted(by[owner], key=lambda e: e['tag'].lower())
            fo.write(f'## {owner} ({len(es)})\n\n')
            fo.write(', '.join(('`' + e['tag'] + '`' + ('' if e['in_vanilla_xml'] else '*')) for e in es) + '\n\n')
        fo.write(f'## Vanilla XML element names with no direct code xref ({len(unparsed)})\n\n')
        fo.write('These are usually object/type *names* used as elements (e.g. `<SpaceUnit Name=...>` children are tags, '
                 'but container names like `Planets` or per-file wrappers), or tags looked up via computed/table strings.\n\n')
        fo.write(', '.join(f'`{t}`' for t in unparsed[:1500]) + '\n')
    print(len(result), 'tags;', len(parsers), 'parser functions;', len(unparsed), 'corpus tags without xref')

if __name__ == '__main__':
    main(*sys.argv[1:7])
