#!/usr/bin/env python3
"""build_ccp_mod.py - builds the ccpgu t02 Capture Control Points probe mod (Mods\\CcpProbe) from the installed game.

  build_ccp_mod.py [--game DIR] [--out MODDIR] [--source-zip extracted\\foc_data_text.zip] [--map _MP_LAND_KAMINO]
                   [--human EMPIRE] [--no-spawn] [--no-invulnerable] [--config-out ccp_config.json] [--session ID]

What it writes (nothing from the game is stored in the repository):
  Data\\Scripts\\FreeStore\\BusyTacticalFreeStore.lua   the shipped script, unchanged, + a generated CCP_CFG table
                                                       + ccp_hook.lua appended
  CCP_PROBE_MARKER.txt                                 lets cleanup (ccp_cleanup.py) recognise the folder as ours
and, with --config-out, the configuration plus the map's expected points (ccp_maps.py) as JSON for the reader / parser.

The human side (default Empire) gets CCP_CFG.squads spawned on every relevant point: capturing infantry (two
companies) and one escort vehicle that cannot capture (Influences_Capture_Point False) but shoots contesting units.
The AI side (the other of Empire / Rebel) runs the hook from its free store.
"""
import argparse
import json
import os
import shutil
import sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
PROBE_MOD = os.path.dirname(HERE)
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(PROBE_MOD, 'common'))
import ted_owners  # noqa: E402
import ccp_maps  # noqa: E402

MOD_NAME = 'CcpProbe'
MARKER = 'CCP_PROBE_MARKER.txt'
FREESTORE = 'DATA\\SCRIPTS\\FREESTORE\\BUSYTACTICALFREESTORE.LUA'
HOOK = os.path.join(HERE, 'ccp_hook.lua')
DEFAULT_MAP = ccp_maps.DEFAULT_MAP
DEFAULT_HUMAN = 'EMPIRE'
ENUM_FRAME = 30          # list the points 1 s into the battle
START_FRAME = 150        # spawn the capturers 5 s in
STOP_FRAME = 54000       # the hook stops recording after 30 min
# Human faction -> (Find_Player name, AI faction, squads). Type names must exist in the FoC XML (selftest checks).
SIDES = {
    'EMPIRE': ('Empire', 'REBEL', [('Imperial_Stormtrooper_Squad', 2), ('AT_AT_Walker', 1)]),
    'REBEL': ('Rebel', 'EMPIRE', [('Rebel_Infantry_Squad', 2), ('T4B_Tank', 1)]),
}
PLAYERS = ('Empire', 'Rebel', 'Neutral')


def config(game, map_name, human, spawn=True, invulnerable=True, session='?'):
    hname, ai, squads = SIDES[human.upper()]
    cfg = {'session': session, 'map': map_name.upper(), 'human': hname, 'human_faction': human.upper(), 'ai': ai,
           'enum_frame': ENUM_FRAME, 'start_frame': START_FRAME, 'stop_frame': STOP_FRAME, 'hb_frames': 90,
           'spawn': bool(spawn), 'invulnerable': bool(invulnerable), 'relevant': list(ccp_maps.RELEVANT),
           'fixed': list(ccp_maps.FIXED), 'squads': [{'type': t, 'n': n} for t, n in squads], 'players': list(PLAYERS),
           'expected': None, 'note': ''}
    try:
        flags = ccp_maps.marker_flags()
        res = ccp_maps.analyse(game, flags) if os.path.isdir(game) else {}
        d = res.get(map_name.upper())
        if d is not None:
            cfg['expected'] = {'source': d['source'], 'tag': d['tag'], 'control': d['control'], 'name_key': d['name_key'],
                               'relevant': d['relevant'], 'fixed': d['fixed'], 'starts': d['starts']}
        else:
            cfg['note'] = 'map %s not readable from %s (offline build?)' % (map_name, game)
    except (OSError, ValueError, KeyError, SystemExit) as e:
        cfg['note'] = 'map read failed: %s' % e
    return cfg


def lua_str(s):
    return '"%s"' % str(s).replace('\\', '\\\\').replace('"', '\\"')


def lua_config(cfg):
    L = ['-- generated by build_ccp_mod.py (map %s): ccpgu t02 Capture Control Points probe settings' % cfg['map'],
         'CCP_CFG = {',
         '\tsession = %s,' % lua_str(cfg['session']),
         '\tmap = %s,' % lua_str(cfg['map']),
         '\thuman = %s,' % lua_str(cfg['human']),
         '\tai = %s,' % lua_str(cfg['ai']),
         '\tenum_frame = %d,' % cfg['enum_frame'],
         '\tstart_frame = %d,' % cfg['start_frame'],
         '\tstop_frame = %d,' % cfg['stop_frame'],
         '\thb_frames = %d,' % cfg['hb_frames'],
         '\tspawn = %s,' % ('true' if cfg['spawn'] else 'false'),
         '\tinvulnerable = %s,' % ('true' if cfg['invulnerable'] else 'false'),
         '\trelevant = { %s },' % ', '.join(lua_str(t) for t in cfg['relevant']),
         '\tfixed = { %s },' % ', '.join(lua_str(t) for t in cfg['fixed']),
         '\tsquads = { %s },' % ', '.join('{ type = %s, n = %d }' % (lua_str(s['type']), s['n']) for s in cfg['squads']),
         '\tplayers = { %s },' % ', '.join(lua_str(p) for p in cfg['players']),
         '}', '']
    return '\n'.join(L)


def freestore_text(game, cfg, source_zip=None):
    tail = lua_config(cfg) + '\n' + open(HOOK, encoding='ascii').read()
    return ted_owners.append_to_shipped(game, FREESTORE, tail, source_zip)


def build(game, out, source_zip=None, map_name=DEFAULT_MAP, human=DEFAULT_HUMAN, config_out=None, spawn=True,
          invulnerable=True, session='?'):
    cfg = config(game, map_name, human, spawn, invulnerable, session)
    if os.path.exists(out):
        if not os.path.exists(os.path.join(out, MARKER)):
            raise SystemExit('refusing to overwrite %s: not a CCP probe folder' % out)
        shutil.rmtree(out)
    fs, src = freestore_text(game, cfg, source_zip)
    p = os.path.join(out, 'Data', 'Scripts', 'FreeStore', 'BusyTacticalFreeStore.lua')
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, 'wb') as f:
        f.write(fs)
    with open(os.path.join(out, MARKER), 'wb') as f:
        f.write(b'ccpgu t02 Capture Control Points probe mod (tools/probe_mod/ccp_probe); removed by cleanup_ccp.cmd\r\n')
    cfg['freestore_source'] = src
    if config_out:
        with open(config_out, 'w') as f:
            json.dump(cfg, f, indent=1, sort_keys=True)
    exp = cfg['expected']
    print('built %s (BusyTacticalFreeStore.lua from %s; map %s, %s relevant point(s)%s)' % (
        out, src, cfg['map'], len(exp['relevant']) if exp else '?', (' note: ' + cfg['note']) if cfg['note'] else ''))
    return p, cfg


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--game', default=ted_owners.DEFAULT_GAME)
    ap.add_argument('--out', help='mod folder (default <game>\\corruption\\Mods\\%s)' % MOD_NAME)
    ap.add_argument('--source-zip', help='read the shipped free-store script from this zip (offline check)')
    ap.add_argument('--map', default=DEFAULT_MAP)
    ap.add_argument('--human', default=DEFAULT_HUMAN, choices=sorted(SIDES))
    ap.add_argument('--no-spawn', action='store_true')
    ap.add_argument('--no-invulnerable', action='store_true')
    ap.add_argument('--config-out')
    ap.add_argument('--session', default='manual')
    a = ap.parse_args()
    build(a.game, a.out or os.path.join(a.game, 'corruption', 'Mods', MOD_NAME), a.source_zip, a.map, a.human,
          a.config_out, not a.no_spawn, not a.no_invulnerable, a.session)
    return 0


if __name__ == '__main__':
    sys.exit(main())
