#!/usr/bin/env python3
"""make_docs.py - render docs/shaders/CATALOG.md from catalog.json (+ decompiled/ dir).

Usage: python -I make_docs.py <out dir containing catalog.json and decompiled/> [validation.json]
"""
import collections
import json
import os
import sys

LOD_ORDER = ["DX9", "DX8ATI", "DX8", "FIXEDFUNCTION", "FF", None]


def best_tech(e):
    techs = [t for t in e["techniques"] if t["name"] != "max_viewport"]
    if not techs:
        return None
    return sorted(techs, key=lambda t: LOD_ORDER.index(t["lod"]) if t["lod"] in LOD_ORDER else 9)[0]


def prof(p, k):
    s = p.get(k)
    if not s:
        return "FF"
    return "%s(%s)" % (s["profile"], s["instructions"])


def code_lines(path):
    try:
        return [l for l in open(path) if not l.startswith("//")]
    except OSError:
        return None


def main(argv):
    out = argv[1]
    cat = json.load(open(os.path.join(out, "catalog.json")))
    val = json.load(open(argv[2])) if len(argv) > 2 else None
    G = cat["games"]
    L = []
    W = L.append
    tot = cat["totals"]
    foc = {e["effect"]: e for e in G["foc"]["effects"]}
    eaw = {e["effect"]: e for e in G.get("eaw", {"effects": []})["effects"]}
    W("# Alamo shader catalog (Star Wars: Empire at War / Forces of Corruption)")
    W("")
    W("Generated by `tools/shaders/build_catalog.py` + `make_docs.py` from the shipped compiled effects "
      "(`Data\\Art\\Shaders\\**\\*.FXO`, D3DX9 fx_2_0). Machine-readable twin: `catalog.json`. "
      "Per-effect reconstructed `.fx` listings, per-shader asm and lifted HLSL-like pseudocode are in "
      "`shaders_decompiled.zip` (`<game>/<EFFECT>/effect.fx.txt, *.asm, *.hlsl`).")
    W("")
    W("## 1. Summary")
    W("")
    W("| | FoC | EaW |")
    W("|---|---:|---:|")
    W("| effects (after patch overrides) | %d | %d |" % (len(foc), len(eaw)))
    for k, lab in (("techniques", "techniques"), ("passes", "passes")):
        W("| %s | %d | %d |" % (lab, sum(len(e["techniques"]) if k == "techniques" else sum(len(t["passes"]) for t in e["techniques"]) for e in foc.values()),
                                 sum(len(e["techniques"]) if k == "techniques" else sum(len(t["passes"]) for t in e["techniques"]) for e in eaw.values())))
    W("| shader programs (per effect) | %d | %d |" % (sum(len(e["shaders"]) for e in foc.values()),
                                                     sum(len(e["shaders"]) for e in eaw.values())))
    W("")
    if val:
        W("**Validation.** fx_2_0 parser: every effect parses to the exact end of file, 0 unknown "
          "state operations, 0 unknown resource usages. Disassembler: %d unique bytecode blobs "
          "(%s); unknown opcodes: %s; every blob ends on the END token with no trailing data. "
          "Cross-check against vkd3d-shader 1.19 (d3dbc -> d3d-asm, built from the Wine tree): "
          "%d/%d blobs give the identical instruction stream (mnemonic, modifiers, register operands; "
          "%d instructions compared). Swizzles/literals were compared separately: the only textual "
          "differences are notation (vkd3d prints `a.x` for `a0.x` and omits `dcl` masks)." % (
              val["blobs"], ", ".join("%s %d" % kv for kv in sorted(val["profiles"].items())),
              val["unknown_opcodes"] or "none", val["match"], val["blobs"],
              val.get("instructions_compared", 0)))
        W("")
    W("Overrides applied (later wins: shaders.meg < Patch.meg < Patch2.meg < 64Patch.meg):")
    W("")
    for g in G:
        for e in G[g]["effects"]:
            if e["overrides"]:
                W("- %s `%s` from **%s** (replaces %s)" % (g, e["path"], e["meg"], ", ".join(e["overrides"])))
    W("")
    # FoC vs EaW
    only_foc = sorted(set(foc) - set(eaw))
    same_code = diff_code = 0
    diff_list = []
    state_diff = []
    for k in sorted(set(foc) & set(eaw)):
        for s in foc[k]["shaders"]:
            a = code_lines(os.path.join(out, "decompiled", "foc", k, s["file"] + ".asm"))
            b = code_lines(os.path.join(out, "decompiled", "eaw", k, s["file"] + ".asm"))
            if b is None:
                continue
            if a == b:
                same_code += 1
            else:
                diff_code += 1
                diff_list.append("%s/%s" % (k, s["file"]))
        fa = code_lines(os.path.join(out, "decompiled", "foc", k, "effect.fx.txt"))
        fb = code_lines(os.path.join(out, "decompiled", "eaw", k, "effect.fx.txt"))
        if fa != fb:
            state_diff.append(k)
    W("**FoC vs EaW.** FoC-only effects: %s. Of the shader programs present in both, %d are "
      "instruction-identical and %d differ (%s). Effects whose parameter/technique/state listing differs: "
      "%d (%s). The binaries also differ in compiler-version strings (CTAB creator), so byte hashes "
      "differ almost everywhere; compare code, not hashes." % (
          ", ".join("`%s`" % x for x in only_foc) or "none", same_code, diff_code,
          ", ".join("`%s`" % x for x in diff_list) or "-", len(state_diff),
          ", ".join("`%s`" % x for x in state_diff[:40]) + (" ..." if len(state_diff) > 40 else "")))
    W("")
    W("## 2. How the engine uses effects")
    W("")
    W("- **Effect metadata** lives in parameters named `_ALAMO_*`: `_ALAMO_RENDER_PHASE` (which render "
      "phase draws it), `_ALAMO_VERTEX_PROC` (Mesh / RSkin / Grass / ShadowVolume / RSkinShadowVolume), "
      "`_ALAMO_VERTEX_TYPE` (the vertex declaration, e.g. `alD3dVertNU2U3U3`), `_ALAMO_TANGENT_SPACE`, "
      "`_ALAMO_SHADOW_VOLUME`, `_ALAMO_Z_SORT` etc.")
    ph = collections.Counter(e["alamo"].get("render_phase") for e in foc.values())
    W("- Render phases declared (FoC): " + ", ".join("%s %d" % (k or "(none: engine/post)", v) for k, v in ph.most_common()) + ".")
    W("- **Phase effects** (`ENGINE\\Phase*.fxo`) have no shaders: pass 0 sets the baseline device state at "
      "the start of a render phase, pass 1 restores it. Material effects only set the states they change, so the "
      "effective pipeline state of a draw = phase baseline + material pass states (see PORTING.md, PSO keys).")
    lods = collections.Counter(tuple(t["lod"] for t in e["techniques"]) for e in foc.values())
    W("- **LOD / fallback ladder.** Techniques carry an annotation `string LOD` with values `DX9` (ps_2_0), "
      "`DX8ATI` (ps_1_4), `DX8` (ps_1_1..1_3), `FIXEDFUNCTION` (no shaders, texture-stage states) and `FF` "
      "(AlamoEngine.fxo). Techniques appear best-first. A leading technique named `max_viewport` (no LOD "
      "annotation) is the 3ds Max viewport preview and is not used by the game. Ladders seen (FoC, incl. max_viewport=None): "
      + "; ".join("%s x%d" % ("/".join(str(x) for x in k), v) for k, v in lods.most_common(8)) + ".")
    W("- The highest shader models used anywhere are **vs_2_0 / ps_2_0**; most vertex shaders are vs_1_1.")
    W("- **Dynamic state expressions (FXLC).** Many passes compute states on the CPU from parameters, e.g. "
      "`AlphaBlendEnable = (m_lightScale.w < 1)` (fade-out makes opaque materials alpha-blended), "
      "`TextureFactor = Colorization`, `MaterialDiffuse = m_lightScale * Diffuse`, and `Texture0` transforms "
      "built from `m_FOWTexU/V` x `m_viewInv` for fog-of-war projection.")
    W("- **Preshaders.** Some vertex shaders carry a D3DX preshader (CPU code run on every CommitChanges) "
      "that computes extra constants (e.g. Grass: wind phase from `m_time`, `BendScale`; SPH lighting "
      "rotated into object space). The lifted `.hlsl` files show these as `cpu:` lines.")
    W("")
    # engine parameter block
    sem = collections.Counter()
    sem_type = {}
    for e in foc.values():
        for p in e["parameters"]:
            if p["semantic"]:
                sem[p["semantic"]] += 1
                sem_type[p["semantic"]] = (p["name"], p["type"] + ("[%d]" % p["elements"] if p["elements"] else ""))
    W("## 3. Engine-supplied parameters (semantics)")
    W("")
    W("Every effect `#include`s the same global block (declared in all %d FoC effects); the engine binds "
      "parameters by semantic. Effects that need more add a few." % len(foc))
    W("")
    W("| semantic | parameter | type | effects |")
    W("|---|---|---|---:|")
    for s, n in sorted(sem.items(), key=lambda kv: (-kv[1], kv[0])):
        W("| `%s` | `%s` | %s | %d |" % (s, sem_type[s][0], sem_type[s][1], n))
    W("")
    sk = [e for e in foc.values() if e.get("skinning")]
    if sk:
        s = sk[0]["skinning"]
        W("**Skinning palette:** `%s : %s`, `%s[%d]` = %d bones x 3 float4 registers = c0..c%d "
          "(rigid skinning, `_ALAMO_BONES_PER_VERTEX = 1`, vertex types `alD3dVertRSkin*`). The vertex shader "
          "reads the bone index from **NORMAL.w** (`v1.w`; the engine packs the ALO bone index there when it builds "
          "the GPU vertex buffer), truncates it (an `expp`.y frac trick), multiplies by 3, `mov a0.x`, then "
          "`dp4`/`dp3` position and normal against `c[a0.x+0..2]`. Used by %d effects: %s." % (
              s["param"], s["semantic"], s["type"], s["elements"], s["elements"],
              s.get("registers_used_max", s["elements"] * 3) - 1, len(sk),
              ", ".join(e["effect"] for e in sk)))
        W("")
    W("**Lighting model:** one directional light (`DIR_LIGHT_*_0`, world and object space), a global "
      "ambient, and two 3-element `float4x4` spherical-harmonic matrices `SPH_LIGHT_ALL` / `SPH_LIGHT_FILL` "
      "(irradiance from all lights / fill lights, evaluated per vertex), modulated by `LIGHT_SCALE` (whose .w "
      "is also the fade alpha).")
    W("")
    # usage table
    W("## 4. Usage by ALO materials")
    W("")
    corp = cat["alo_corpus"]
    W("Three corpora. **FoC** = FoC `models.meg` + Patch/Patch2 (own parser, has the per-mesh hidden flag "
      "and triangle counts). **EaW** = EaW `models.meg` (assets-stream export `eaw_alo_materials.json`, "
      "no hidden flag / vertex data) + EaW patch/patch2. **Combined** = what FoC actually loads if it mounts "
      "EaW `GameData` underneath its own `Data` (the FoC exe contains the string `..\\GameData\\`; mount "
      "order still to be confirmed by RE): FoC models shadow EaW models of the same name.")
    W("")
    W("| corpus | ALOs with meshes | ALOs without meshes (particles / skeleton-only) |")
    W("|---|---:|---:|")
    for k in ("foc", "eaw", "combined"):
        if k in corp:
            W("| %s | %d | %d |" % (k, corp[k]["models"], corp[k]["particle_systems"]))
    W("")
    W("A *submesh* is one material = one draw call per model instance. *Drawn* excludes submeshes with the "
      "hidden flag (FoC) and, where the flag is unknown (EaW), the never-drawn materials `alDefault.fx`, "
      "`Default.fx` and `MeshCollision.fx` (see below). Note that the FoC hidden flag also marks meshes that the "
      "game toggles at runtime (muzzle flashes, shields, damage states), so *drawn* is a lower bound for "
      "MeshAdditive/MeshShield.")
    W("")

    def corpus_rows(key):
        rows = []
        src = eaw.values() if key == "eaw" else foc.values()
        for e in src:
            a = (e.get("alo_combined") if key == "combined" else e.get("alo")) or {}
            rows.append((a.get("visible_submeshes", 0), a.get("submeshes", 0), e, a))
        rows.sort(key=lambda r: (-r[0], -r[1], r[2]["effect"]))
        return rows

    R = {k: corpus_rows(k) for k in ("foc", "eaw", "combined")}
    W("### 4.1 Top effects by drawn submeshes")
    W("")
    W("| # | FoC | drawn | EaW | drawn | Combined (FoC over EaW) | drawn | cum. % |")
    W("|---:|---|---:|---|---:|---|---:|---:|")
    tot_c = sum(r[0] for r in R["combined"]) or 1
    cum = 0
    for i in range(15):
        cells = []
        for k in ("foc", "eaw", "combined"):
            r = R[k][i] if i < len(R[k]) else None
            cells += ["`%s`" % r[2]["effect"] if r and r[0] else "-", str(r[0]) if r and r[0] else "-"]
        cum += R["combined"][i][0] if i < len(R["combined"]) else 0
        W("| %d | %s | %.1f |" % (i + 1, " | ".join(cells), 100.0 * cum / tot_c))
    W("")
    for key, label in (("foc", "FoC"), ("eaw", "EaW"), ("combined", "Combined")):
        tv = sum(r[0] for r in R[key])
        tu = sum(r[3].get("unique_param_sets", 0) for r in R[key])
        tc = sum(r[3].get("unique_const_sets", 0) for r in R[key])
        top10 = sum(r[0] for r in R[key][:10])
        if tv:
            W("- **%s:** %d drawn submeshes; top 10 effects = %.1f%%. Redundancy: %d distinct (effect, all params "
              "incl. textures) sets = **%.0f%% redundant**; %d distinct numeric-constant sets = **%.0f%% redundant**." % (
                  label, tv, 100.0 * top10 / tv, tu, 100 * (1 - tu / tv), tc, 100 * (1 - tc / tv)))
    W("")
    W("### 4.2 Never-drawn materials: alDefault.fx, Default.fx, MeshCollision.fx")
    W("")
    nd = []
    for key, label in (("foc", "FoC"), ("eaw", "EaW"), ("combined", "Combined")):
        miss = G["foc"].get("combined_alo_shaders_without_fxo", {}) if key == "combined" else G[key]["alo_shaders_without_fxo"]
        mc = next((r[3] for r in R[key] if r[2]["effect"] == "MESHCOLLISION"), {})
        nd.append("%s: alDefault %d, Default %d, MeshCollision %d submeshes" % (
            label, miss.get("ALDEFAULT", {}).get("submeshes", 0), miss.get("DEFAULT", {}).get("submeshes", 0),
            mc.get("submeshes", 0)))
    W("Counts: " + "; ".join(nd) + ".")
    W("")
    W("- `alDefault.fx` / `Default.fx` have **no FXO anywhere** (not in shaders.meg or any patch), so the engine "
      "cannot draw them with an effect. In FoC 927 of 931 alDefault submeshes and all 21 Default submeshes carry "
      "the hidden flag; their mesh names are collision hulls (`*_COLL`), hard-point / UI proxies (`HEALTH_*`, "
      "`SELECT_*`, `BUILD_PAD*`, `SHIELD_*`, `BUTTON_*`) and attachment markers. They are **collision / proxy "
      "geometry, not drawn**. The port should load them into the collision/proxy system only and skip them in the "
      "renderer (optionally a debug wireframe).")
    W("- `MeshCollision.fx` exists (DX8 vs_1_1 + ps_1_1 solid colour `Color`, plus an FF fallback). In FoC 296 of 297 "
      "submeshes are hidden: it is the **debug visualisation of collision hulls**, drawn only in debug views. Treat "
      "as debug-only. The EaW `models.meg` export has no hidden flag, but the same exporter conventions apply.")
    W("- Other ALO shader names with no FXO: " + (", ".join("`%s` (%d submesh%s)" % (k, v["submeshes"], "" if v["submeshes"] == 1 else "es")
        for k, v in G["foc"].get("combined_alo_shaders_without_fxo", {}).items() if k not in ("ALDEFAULT", "DEFAULT")) or "none")
      + ". The renderer should log these through the mod-diagnostics channel and fall back to MeshGloss.")
    W("")
    # ALO params not declared by the effect
    und = []
    for e in foc.values():
        a = e["alo"]
        if not a:
            continue
        decl = {p["name"] for p in e["parameters"]} | {t["name"] for t in e["textures"]}
        extra = {k: v for k, v in a["params_seen"].items() if k not in decl}
        if extra:
            und.append("`%s`: %s" % (e["effect"], ", ".join("%s x%d" % kv for kv in extra.items())))
    if und:
        W("ALO material parameters **not declared** by the effect (ignored by D3DX SetValue; candidates for "
          "the mod diagnostics log): " + "; ".join(und) + ".")
        W("")
    # per effect detail
    W("## 5. Effect reference (FoC; EaW identical unless noted above)")
    W("")
    for name in sorted(foc):
        e = foc[name]
        a = e["alo"]
        W("### %s" % name)
        W("")
        meta = ", ".join("%s=%s" % (k, v) for k, v in e["alamo"].items())
        W("`%s` (%d bytes%s). %s" % (e["path"], e["bytes"], ", from %s" % e["meg"] if e["meg"] != "shaders" else "",
                                     meta or "no _ALAMO_ metadata"))
        if a:
            W("ALO: %d submeshes (%d visible) in %d models; vertex formats %s." % (
                a["submeshes"], a["visible_submeshes"], a["models"],
                ", ".join("%s x%d" % kv for kv in a["vertex_formats"].items())))
        W("")
        mats = [p for p in e["parameters"] if p["name"] in e["material_parameters"]]
        if mats:
            W("- material params: " + ", ".join("`%s %s = %s`" % (p["type"], p["name"], json.dumps(p.get("default"))) for p in mats))
        texs = [t for t in e["textures"] if not t["semantic"]]
        if texs:
            W("- textures: " + ", ".join("`%s`" % t["name"] for t in texs))
        for s in e["samplers"]:
            W("- sampler `%s` <- `%s`: %s" % (s["name"], s["texture"], ", ".join("%s=%s" % kv for kv in s["states"].items()) or "defaults"))
        extra_sem = [p["semantic"] for p in e["parameters"] if p["semantic"] and sem[p["semantic"]] < len(foc)]
        if extra_sem:
            W("- extra engine semantics: " + ", ".join("`%s`" % x for x in extra_sem))
        for t in e["techniques"]:
            if t["name"] == "max_viewport":
                continue
            for p in t["passes"]:
                ex = "; ".join("%s: %s" % (k, v) for k, v in p["expressions"].items())
                W("- `%s` [%s] `%s`: VS %s, PS %s; %s%s" % (
                    t["name"], t["lod"], p["name"], prof(p, "vs"), prof(p, "ps"), p["summary"] or "no state changes",
                    ("; expr: " + ex) if ex else ""))
        W("")
    open(os.path.join(out, "CATALOG.md"), "w").write("\n".join(L) + "\n")
    print("wrote", os.path.join(out, "CATALOG.md"), len(L), "lines")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
