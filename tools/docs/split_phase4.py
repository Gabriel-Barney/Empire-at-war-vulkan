#!/usr/bin/env python3
"""Split docs/PHASE4.md: keep the short stable parts, move every dated detail section to docs/status/<slug>.md.

docs/PHASE4.md grew to 338 KB / 927 lines and was edited by 126 commits in a week. The stable parts stay (title and preamble,
At a glance, Decisions, G0, Steps, Open items); every other `## Title (ids, YYYY-MM-DD)` section moves verbatim to
docs/status/<slug>.md and is replaced by one row of a generated index (title, ids, date, link) between the markers

    <!-- status-index:begin ... -->  ...  <!-- status-index:end -->

Future work appends to its own status file (or creates a new docs/status/<slug>.md) instead of PHASE4.md. The splitter is
re-runnable: a dated section that shows up in PHASE4.md again is moved (appended to its status file when one with that slug
exists), and the index is regenerated from every docs/status/*.md, so a second run changes nothing.

Rules (they work on the current file and on later versions of it):
  * A section is a block that starts with a `## ` heading (outside code fences) and ends before the next `## ` heading.
  * KEPT: the text before the first `## `, the sections named At a glance / Decisions / G0 / Steps / Open items (add names
    with --keep-name), and any section whose heading has no trailing dated group (they are listed in the report).
  * MOVED: a heading ending in `(<ids>, YYYY-MM-DD)` (any parenthesised group containing an ISO date) or in ` - YYYY-MM-DD`
    / ` — YYYY-MM-DD`, that is not a kept name.
  * Slug: the heading title without its trailing group, lower case, non-alphanumerics to `-`, at most 60 characters
    (cut at a word boundary), `-2`, `-3` ... for a second section with the same slug in one run. The date is not in the slug,
    so later work on the same topic appends to the same file.
  * The moved text is byte for byte the original (heading included): nothing is rewritten, so nothing is lost.

Usage:
  python tools/docs/split_phase4.py --dry-run [--out-dir DIR]   write the result to a scratch dir, print the size/line report
  python tools/docs/split_phase4.py --check                     dry run + prove that nothing is lost (exit 1 when it is)
  python tools/docs/split_phase4.py --apply                     write docs/PHASE4.md and docs/status/*.md in place and fix
                                                                the references listed as fixable (below)
  python tools/docs/split_phase4.py --selftest

--check: concatenating the pieces in their original order (kept text and moved sections, read back from the files that were
written) gives the input again (the old generated index block aside); a second run on the result changes nothing.

References: the repository's tracked text files are scanned for lines that mention PHASE4 and a moved section (its title,
its heading anchor, or one of its ids such as `OPT3 t07`). The report lists every one. With --apply, a reference of the exact
form `docs/PHASE4.md "<moved title>"` in a non-document file (CMake, scripts, sources: not .md / .html / .txt / .json) is
rewritten to `docs/status/<slug>.md`; documents are only listed, update them by hand. --refs-out FILE writes the list.
Exit: 0 ok, 1 --check failed, 2 usage / unreadable input.
"""
from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
import tempfile
from dataclasses import dataclass, field

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
STABLE = ("at a glance", "decisions", "g0", "steps", "open items")
BEGIN = "<!-- status-index:begin (generated by tools/docs/split_phase4.py; edit the status files, not this block) -->"
END = "<!-- status-index:end -->"
BEGIN_RE = re.compile(r"^<!-- status-index:begin\b.*-->[ \t]*$", re.M)
END_RE = re.compile(r"^<!-- status-index:end -->[ \t]*$", re.M)
ISO = r"\d{4}-\d{2}-\d{2}"
HEAD_PAREN = re.compile(rf"^##[ \t]+(?P<title>.*?)[ \t]*\((?P<paren>[^()]*{ISO}[^()]*)\)[ \t]*$")
HEAD_DASH = re.compile(rf"^##[ \t]+(?P<title>.*?)[ \t]+[-–—][ \t]+(?P<paren>{ISO})[ \t]*$")
MAX_SLUG = 60


@dataclass
class Chunk:
    kind: str  # "keep" | "move" | "index"
    text: str
    title: str = ""
    ids: str = ""
    date: str = ""
    slug: str = ""
    start_line: int = 0
    note: str = ""  # why a section is kept (report)


@dataclass
class Plan:
    chunks: list[Chunk] = field(default_factory=list)
    old_index: str | None = None


def split_h2(text: str, first_line: int = 1) -> list[tuple[str, int]]:
    """Cuts text at every `## ` heading outside code fences: [(piece, start_line)]; the first piece is the text before it."""
    pieces: list[tuple[str, int]] = []
    cur: list[str] = []
    start = first_line
    fence = None
    for no, line in enumerate(text.splitlines(keepends=True), first_line):
        s = line.lstrip()
        if fence is None and (s.startswith("```") or s.startswith("~~~")):
            fence = s[:3]
        elif fence is not None and s.startswith(fence):
            fence = None
        elif fence is None and line.startswith("## "):
            if cur:
                pieces.append(("".join(cur), start))
            cur, start = [], no
        cur.append(line)
    if cur:
        pieces.append(("".join(cur), start))
    return pieces


def classify(piece: str, start: int, keep_names: tuple[str, ...]) -> Chunk:
    first = piece.split("\n", 1)[0].rstrip("\r")
    if not first.startswith("## "):
        return Chunk("keep", piece, start_line=start, note="text before the first section")
    title_all = first[3:].strip()
    low = title_all.lower()
    for name in keep_names:
        if low.startswith(name) and re.match(r"^\s*([—–:(-]|$)", low[len(name):]):
            return Chunk("keep", piece, title=title_all, start_line=start, note="stable section")
    m = HEAD_PAREN.match(first) or HEAD_DASH.match(first)
    if not m:
        return Chunk("keep", piece, title=title_all, start_line=start, note="no trailing dated group: kept")
    paren = m.group("paren")
    date = re.findall(ISO, paren)[-1]
    ids = re.sub(r"\s*,?\s*" + ISO + r"\s*,?\s*", ", ", paren).strip(" ,")
    ids = re.sub(r"(,\s*)+", ", ", ids).strip(" ,")
    return Chunk("move", piece, title=m.group("title").strip(), ids=ids, date=date, start_line=start)


def make_plan(text: str, keep_names=STABLE) -> Plan:
    plan = Plan()
    b, e = BEGIN_RE.search(text), END_RE.search(text)
    if bool(b) != bool(e) or (b and e and e.start() < b.start()):
        raise SystemExit("split_phase4: unbalanced status-index markers in the input")
    if b and e:
        end = block_end(text, e)
        plan.old_index = text[b.start():end]
        parts = [(text[:b.start()], 1), (text[end:], text.count("\n", 0, end) + 1)]
        # an index block starts with its own H2 heading right after the marker; the text before the block is cut at H2 too
        pre, post = parts
        for piece, start in split_h2(pre[0], pre[1]):
            plan.chunks.append(classify(piece, start, keep_names))
        plan.chunks.append(Chunk("index", plan.old_index, start_line=text.count("\n", 0, b.start()) + 1))
        for piece, start in split_h2(post[0], post[1]):
            plan.chunks.append(classify(piece, start, keep_names))
    else:
        for piece, start in split_h2(text):
            plan.chunks.append(classify(piece, start, keep_names))
    # slugs
    used: dict[str, int] = {}
    for c in plan.chunks:
        if c.kind != "move":
            continue
        base = slugify(c.title)
        n = used.get(base, 0) + 1
        used[base] = n
        c.slug = base if n == 1 else f"{base}-{n}"
    return plan


def slugify(title: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-") or "section"
    if len(s) > MAX_SLUG:
        cut = s[:MAX_SLUG]
        if "-" in cut and s[MAX_SLUG] != "-":
            cut = cut[:cut.rfind("-")]
        s = cut.strip("-")
    return s


def github_anchor(heading: str) -> str:
    h = re.sub(r"^#+\s*", "", heading).strip().lower()
    h = re.sub(r"[^\w\- ]", "", h)
    return h.replace(" ", "-")


def first_heading(text: str) -> tuple[str, str, str]:
    """(title, ids, date) of a status file's first `## ` heading (title: the heading text when it has no dated group)."""
    for piece, _ in split_h2(text):
        if piece.startswith("## "):
            c = classify(piece, 0, ())
            if c.kind == "move":
                return c.title, c.ids, c.date
            return piece.split("\n", 1)[0][3:].strip(), "", ""
    return "", "", ""


def build_index(status: dict[str, str]) -> str:
    rows = []
    for name, text in status.items():
        title, ids, date = first_heading(text)
        rows.append((date or "9999-99-99", name, title or name, ids))
    rows.sort()
    out = [BEGIN, "## Detail status files (`docs/status/`)", "",
           "Each section that used to sit in this file is now `docs/status/<slug>.md` (verbatim). New detail goes into its own status file",
           "(append a dated section to an existing one or add a new file), not here; `python tools/docs/split_phase4.py --apply` moves a dated",
           "`## Title (ids, YYYY-MM-DD)` section that lands here anyway and regenerates this table.", "",
           "| Section | Ids | Date | File |", "|---|---|---|---|"]
    for date, name, title, ids in rows:
        out.append(f"| {title} | {ids} | {'' if date.startswith('9999') else date} | [{name}](status/{name}) |")
    out += [END]
    return "\n".join(out) + "\n\n"  # the end marker line, then one blank line


def load_status(status_dir: str) -> dict[str, str]:
    out: dict[str, str] = {}
    if os.path.isdir(status_dir):
        for n in sorted(os.listdir(status_dir)):
            if n.endswith(".md"):
                with open(os.path.join(status_dir, n), encoding="utf-8", newline="") as f:
                    out[n] = f.read()
    return out


def apply_plan(plan: Plan, status: dict[str, str]) -> tuple[str, dict[str, str], list[Chunk]]:
    """The new PHASE4.md text, the new status dict (existing files with moved sections appended) and the moved chunks."""
    moved = [c for c in plan.chunks if c.kind == "move"]
    new_status = dict(status)
    for c in moved:
        name = c.slug + ".md"
        if name in new_status:
            new_status[name] = new_status[name].rstrip("\n") + "\n\n" + c.text
        else:
            new_status[name] = c.text
    have_index = any(c.kind == "index" for c in plan.chunks)
    index_text = None
    if have_index or moved or new_status:
        index_text = build_index(new_status)
    out: list[str] = []
    inserted = have_index
    for c in plan.chunks:
        if c.kind == "keep":
            out.append(c.text)
        elif c.kind == "index":
            out.append(index_text or "")
        elif not inserted:  # first moved section: the index goes here
            out.append(index_text or "")
            inserted = True
    return "".join(out), new_status, moved


def block_end(text: str, end_match) -> int:
    """End of an index block: after the end marker line, its newline and one blank line (a block always ends with two newlines)."""
    end = end_match.end()
    if text[end:end + 1] == "\n":
        end += 1
        if text[end:end + 1] == "\n":
            end += 1
    return end


def strip_index(text: str) -> tuple[str, str | None]:
    b, e = BEGIN_RE.search(text), END_RE.search(text)
    if not (b and e):
        return text, None
    end = block_end(text, e)
    return text[:b.start()] + text[end:], text[b.start():end]


def check_lossless(orig: str, plan: Plan, new_main: str, out_dir: str, moved: list[Chunk], status_before: dict[str, str]) -> list[str]:
    """Reads the written files back and proves that kept text + moved sections in the original order give the input."""
    problems: list[str] = []
    with open(os.path.join(out_dir, "PHASE4.md"), encoding="utf-8", newline="") as f:
        written_main = f.read()
    if written_main != new_main:
        problems.append("written PHASE4.md differs from the computed text")
    kept_text, index_block = strip_index(written_main)
    if index_block is None and (moved or any(c.kind == "index" for c in plan.chunks)):
        problems.append("no index block in the written PHASE4.md")
    want_kept = "".join(c.text for c in plan.chunks if c.kind == "keep")
    if kept_text != want_kept:
        problems.append("the kept text in PHASE4.md is not the kept sections of the input in order")
    status_now = load_status(os.path.join(out_dir, "status"))
    pos = 0
    rebuilt: list[str] = []
    for c in plan.chunks:
        if c.kind == "keep":
            rebuilt.append(kept_text[pos:pos + len(c.text)])
            pos += len(c.text)
        elif c.kind == "move":
            name = c.slug + ".md"
            body = status_now.get(name, "")
            before = status_before.get(name)
            if not body.endswith(c.text):
                problems.append(f"status/{name} does not end with the moved section '{c.title}'")
                rebuilt.append("")
            else:
                if before is not None and not body.startswith(before.rstrip("\n")):
                    problems.append(f"status/{name} lost its earlier content")
                rebuilt.append(c.text)
        # the old index block is generated: not part of the comparison
    expect = "".join(c.text for c in plan.chunks if c.kind != "index")
    if "".join(rebuilt) != expect:
        problems.append("kept text and moved sections in their original order do not reproduce the input")
    if sum(len(c.text) for c in plan.chunks if c.kind != "index") + (len(plan.old_index) if plan.old_index else 0) != len(orig):
        problems.append("the chunks do not cover the input")
    # fixed point: a second run on the result moves nothing and changes nothing
    plan2 = make_plan(written_main)
    main2, status2, moved2 = apply_plan(plan2, status_now)
    if moved2 or main2 != written_main or status2 != status_now:
        problems.append("a second run on the result changes it (not idempotent)")
    return problems


# ---------------------------------------------------------------------------------------------------------- references
TEXT_EXT = {".md", ".txt", ".cmake", ".cmd", ".bat", ".ps1", ".py", ".cpp", ".hpp", ".h", ".c", ".cc", ".json", ".yml", ".yaml", ".html",
            ".toml", ".ini", ".cfg", ".sh", ".hlsl", ".glsl", ".lua", ".xml", ".csv"}
DOC_EXT = {".md", ".html", ".txt", ".json", ".csv", ".xml"}
SKIP_FILES = {"ROADMAP.html", "docs/ROADMAP.html", "INDEX.json"}  # generated by the roadmap store
PHASE4_RE = re.compile(r"PHASE4(?!_)")


def tracked_files(root: str) -> list[str]:
    r = subprocess.run(["git", "ls-files"], cwd=root, capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit("git ls-files failed: " + r.stderr.strip())
    return [p for p in r.stdout.splitlines() if p]


def is_doc(rel: str) -> bool:
    base = os.path.basename(rel)
    return os.path.splitext(base)[1].lower() in DOC_EXT and base != "CMakeLists.txt"


def find_references(root: str, moved: list[Chunk], skip: set[str]) -> list[dict]:
    """Lines that mention PHASE4 and a moved section (title in any quoting, heading anchor, or an id like 'OPT3 t07')."""
    titles = [(c, c.title.lower()) for c in moved if len(c.title) >= 8]
    anchors = [(c, github_anchor("## " + c.title)) for c in moved]
    id_tokens: list[tuple[Chunk, str]] = []
    for c in moved:
        for tok in re.split(r"\s*,\s*", c.ids):
            tok = tok.strip()
            if re.fullmatch(r"[A-Za-z][A-Za-z0-9]*\d? t\d+[a-z]?", tok) or re.fullmatch(r"[A-Za-z]+\d+[a-z]? t\d+", tok):
                id_tokens.append((c, tok))
    refs = []
    for rel in tracked_files(root):
        ext = os.path.splitext(rel)[1].lower()
        if rel in skip or rel.replace("\\", "/") in SKIP_FILES or rel.startswith("docs/status/") or rel == "docs/PHASE4.md":
            continue
        if ext not in TEXT_EXT and os.path.basename(rel) != "CMakeLists.txt":
            continue
        path = os.path.join(root, rel)
        try:
            if os.path.getsize(path) > 8_000_000:
                continue
            with open(path, encoding="utf-8", errors="replace", newline="") as f:
                lines = f.read().split("\n")
        except OSError:
            continue
        for no, line in enumerate(lines, 1):
            if not PHASE4_RE.search(line):
                continue
            low = line.lower()
            hit = None
            for c, t in titles:
                if t in low:
                    hit = (c, "title")
                    break
            if not hit:
                for c, a in anchors:
                    if "#" + a[:30] in low:
                        hit = (c, "anchor")
                        break
            if not hit:
                for c, tok in id_tokens:
                    if tok.lower() in low:
                        hit = (c, "id " + tok)
                        break
            if hit:
                refs.append({"file": rel, "line": no, "text": line.strip()[:200], "section": hit[0].title, "slug": hit[0].slug,
                             "match": hit[1], "doc": is_doc(rel)})
    return refs


def ref_pattern(c: Chunk) -> re.Pattern:
    """`docs/PHASE4.md "<moved title>"` (also with a backslash path, and with a comma after .md): the one form that is rewritten."""
    return re.compile(r'docs([/\\])PHASE4\.md,? "' + re.escape(c.title) + '"')


def fixable(ref_line: str, moved: list[Chunk]) -> tuple[str, str] | None:
    """(old, new) when the line has the exact form `docs/PHASE4.md "<moved title>"`; else None."""
    for c in moved:
        m = ref_pattern(c).search(ref_line)
        if m:
            sep = m.group(1)
            return m.group(0), f"docs{sep}status{sep}{c.slug}.md"
    return None


def fix_references(root: str, refs: list[dict], moved: list[Chunk], apply: bool) -> list[str]:
    done = []
    by_file: dict[str, list[dict]] = {}
    for r in refs:
        if not r["doc"]:
            by_file.setdefault(r["file"], []).append(r)
    for rel, items in sorted(by_file.items()):
        path = os.path.join(root, rel)
        with open(path, encoding="utf-8", newline="") as f:
            text = f.read()
        new = text
        for c in moved:
            pat = ref_pattern(c)
            for m in pat.finditer(new):
                done.append(f"{rel}: {m.group(0)} -> docs{m.group(1)}status{m.group(1)}{c.slug}.md")
            new = pat.sub(lambda m, c=c: f"docs{m.group(1)}status{m.group(1)}{c.slug}.md", new)
        if new != text and apply:
            with open(path, "w", encoding="utf-8", newline="") as f:
                f.write(new)
    return done


# -------------------------------------------------------------------------------------------------------------- report
def kb(n: int) -> str:
    return f"{n / 1024:,.1f} KB"


def report(orig: str, new_main: str, plan: Plan, moved: list[Chunk], new_status: dict[str, str], status_before: dict[str, str], out_dir: str) -> str:
    L = []
    L.append(f"PHASE4.md: {orig.count(chr(10)) + 1} lines / {len(orig.encode()):,} bytes ({kb(len(orig.encode()))}) -> "
             f"{new_main.count(chr(10)) + 1} lines / {len(new_main.encode()):,} bytes ({kb(len(new_main.encode()))})")
    mb = sum(len(c.text.encode()) for c in moved)
    ml = sum(c.text.count("\n") for c in moved)
    L.append(f"moved {len(moved)} dated sections ({ml} lines, {kb(mb)}) to docs/status/ ({len(new_status)} files after; {len(status_before)} before)")
    L.append(f"written to: {out_dir}")
    L.append("")
    L.append(f"{'lines':>6} {'KB':>7}  {'date':10}  file  <- section [ids]")
    for c in moved:
        L.append(f"{c.text.count(chr(10)):>6} {len(c.text.encode()) / 1024:>7.1f}  {c.date:10}  status/{c.slug}.md  <- {c.title} [{c.ids}]")
    L.append("")
    kept = [c for c in plan.chunks if c.kind == "keep"]
    L.append("kept in PHASE4.md:")
    for c in kept:
        label = c.title or "(text before the first section)"
        L.append(f"{c.text.count(chr(10)):>6} {len(c.text.encode()) / 1024:>7.1f}  {label[:90]}" + (f"   <- {c.note}" if c.note and c.note != "stable section" else ""))
    odd = [c for c in kept if c.note.startswith("no trailing dated group")]
    if odd:
        L.append("")
        L.append(f"note: {len(odd)} kept section(s) have no `(ids, YYYY-MM-DD)` heading, so the splitter leaves them: " + "; ".join(c.title for c in odd))
    return "\n".join(L)


def write_tree(out_dir: str, status_dir: str, main_text: str, status: dict[str, str], only_changed: dict[str, str] | None = None) -> None:
    os.makedirs(status_dir, exist_ok=True)
    with open(os.path.join(out_dir, "PHASE4.md"), "w", encoding="utf-8", newline="") as f:
        f.write(main_text)
    for name, text in status.items():
        if only_changed is not None and only_changed.get(name) == text:
            continue
        with open(os.path.join(status_dir, name), "w", encoding="utf-8", newline="") as f:
            f.write(text)


def inner_mentions(plan: Plan, moved: list[Chunk]) -> list[str]:
    """Quoted mentions of a moved section in the text that stays in PHASE4.md (they now point at a status file)."""
    out = []
    pats = [(c, re.compile(r"[\"“`']" + re.escape(c.title) + r"[\"”`']", re.I)) for c in moved if len(c.title) >= 8]
    for ch in plan.chunks:
        if ch.kind != "keep":
            continue
        for i, line in enumerate(ch.text.split("\n")):
            for c, p in pats:
                if p.search(line):
                    out.append(f"  PHASE4.md:{ch.start_line + i} mentions \"{c.title}\" -> docs/status/{c.slug}.md: {line.strip()[:140]}")
    return out


def run(args) -> int:
    main_path = args.input or os.path.join(ROOT, "docs", "PHASE4.md")
    status_dir = args.status_dir or os.path.join(os.path.dirname(main_path), "status")
    try:
        with open(main_path, encoding="utf-8", newline="") as f:
            orig = f.read()
    except OSError as e:
        print(f"split_phase4: {e}", file=sys.stderr)
        return 2
    keep_names = STABLE + tuple(n.lower() for n in (args.keep_name or []))
    plan = make_plan(orig, keep_names)
    status_before = load_status(status_dir)
    new_main, new_status, moved = apply_plan(plan, status_before)

    # Always compute into a scratch dir first and check it there; --apply copies only a result that passed.
    scratch = args.out_dir or tempfile.mkdtemp(prefix="split_phase4_")
    sdir = os.path.join(scratch, "status")
    if os.path.isdir(sdir):
        for n in os.listdir(sdir):
            if n.endswith(".md"):
                os.remove(os.path.join(sdir, n))
    write_tree(scratch, sdir, new_main, new_status)
    print(report(orig, new_main, plan, moved, new_status, status_before, scratch))

    problems = check_lossless(orig, plan, new_main, scratch, moved, status_before)
    rc = 0
    print()
    if problems:
        rc = 1
        print("CHECK FAILED:\n  " + "\n  ".join(problems))
    else:
        print(f"check ok: {len(moved)} moved sections + {sum(1 for c in plan.chunks if c.kind == 'keep')} kept pieces, read back from the written "
              "files in their original order, reproduce the input (the old generated index block aside); a second run changes nothing")

    refs = find_references(ROOT, moved, set()) if (moved and not args.no_refs) else []
    fixes = fix_references(ROOT, refs, moved, apply=args.apply and rc == 0)
    lines = []
    if refs:
        lines.append(f"references to moved sections ({len(refs)} lines in {len({r['file'] for r in refs})} files; scan: tracked text files, "
                     "not the generated ROADMAP.html pages):")
        for r in refs:
            tag = "document: update by hand" if r["doc"] else "code / script"
            lines.append(f"  {r['file']}:{r['line']} [{r['match']}] -> docs/status/{r['slug']}.md  ({tag})")
            lines.append(f"      {r['text']}")
        lines.append("")
        lines.append(("fixed" if args.apply else "fixable, applied with --apply") + f" in non-document files ({len(fixes)}):")
        lines += ["  " + f for f in fixes] or ["  none"]
    elif not args.no_refs:
        lines.append("references: none found")
    inner = inner_mentions(plan, moved)
    if inner:
        lines.append("")
        lines.append(f"quoted mentions of a moved section inside the text that stays in PHASE4.md ({len(inner)}):")
        lines += inner
    refs_path = args.refs_out or os.path.join(scratch, "references.txt")
    with open(refs_path, "w", encoding="utf-8", newline="") as f:
        f.write("\n".join(lines) + "\n")
    shown = lines if len(lines) <= 120 else lines[:120] + [f"  ... {len(lines) - 120} more lines: full list in {refs_path}"]
    print()
    print("\n".join(shown))
    print(f"\n(reference list written to {refs_path})")

    if args.apply and rc == 0:
        write_tree(os.path.dirname(os.path.abspath(main_path)), status_dir, new_main, new_status, only_changed=status_before)
        print(f"\napplied: {main_path} and {len(new_status)} status file(s) in {status_dir}")
    elif args.apply:
        print("\nnot applied: the check failed")
    else:
        print(f"\ndry run: nothing in the repository was changed (result in {scratch})")
    return rc


def selftest() -> int:
    fails = 0

    def check(c, what):
        nonlocal fails
        if not c:
            print("selftest FAIL:", what)
            fails += 1

    doc = ("# Title\n\nintro\n\n## At a glance\n\nglance\n\n## Decisions (Gabriel, 2026-10-27)\n\nd1\n\n### Sub (2026-10-28)\n\nsub text\n\n"
           "## Steps\n\n| a | b |\n|---|---|\n\n## Worker-count check (OPT3 t07, 2026-11-02)\n\nw text\n```\n## not a heading (x, 2026-01-01)\n```\n\n"
           "## Alpha (OPT1 t07, OPT2 t05, 2026-11-02)\n\nalpha\n\n## Alpha (OPT9, 2026-11-03)\n\nalpha two\n\n"
           "## Dash style - 2026-11-04\n\ndash\n\n## Undated thing\n\nundated\n\n## Open items\n\nopen\n")
    plan = make_plan(doc)
    kinds = [(c.kind, c.title) for c in plan.chunks]
    check([k for k, _ in kinds] == ["keep", "keep", "keep", "keep", "move", "move", "move", "move", "keep", "keep"], f"kinds {kinds}")
    mv = [c for c in plan.chunks if c.kind == "move"]
    check([c.slug for c in mv] == ["worker-count-check", "alpha", "alpha-2", "dash-style"], "slugs " + str([c.slug for c in mv]))
    check(mv[1].ids == "OPT1 t07, OPT2 t05" and mv[1].date == "2026-11-02", "ids/date " + mv[1].ids)
    check("## not a heading" in mv[0].text, "fenced heading stays inside its section")
    with tempfile.TemporaryDirectory() as d:
        main, status, moved = apply_plan(plan, {})
        check(BEGIN in main and END in main and "(status/worker-count-check.md)" in main, "index block")
        check(main.index(BEGIN) < main.index("## Open items") and main.index(BEGIN) > main.index("## Steps"), "index at the first moved section")
        check("w text" not in main and "## Undated thing" in main, "moved text removed, undated kept")
        with open(os.path.join(d, "PHASE4.md"), "w", encoding="utf-8", newline="") as f:
            f.write(main)
        os.makedirs(os.path.join(d, "status"))
        for n, t in status.items():
            with open(os.path.join(d, "status", n), "w", encoding="utf-8", newline="") as f:
                f.write(t)
        check(check_lossless(doc, plan, main, d, moved, {}) == [], "lossless + idempotent")
        # a later version: new dated section appended to a doc that already has an index and status files
        later = main.replace("## Open items", "## Beta (OPT4 t01, 2026-11-10)\n\nbeta\n\n## Alpha (OPT9 t02, 2026-11-12)\n\nalpha three\n\n## Open items")
        plan2 = make_plan(later)
        main2, status2, moved2 = apply_plan(plan2, status)
        check([c.slug for c in moved2] == ["beta", "alpha"], "later moved " + str([c.slug for c in moved2]))
        check(status2["alpha.md"].endswith("alpha three\n\n") and status2["alpha.md"].startswith("## Alpha (OPT1"), "appended to the existing file")
        check(main2.count(BEGIN) == 1 and "(status/beta.md)" in main2, "index regenerated in place")
        check(main2.index(BEGIN) == main.index(BEGIN), "index stays where it was")
        with open(os.path.join(d, "PHASE4.md"), "w", encoding="utf-8", newline="") as f:
            f.write(main2)
        for n, t in status2.items():
            with open(os.path.join(d, "status", n), "w", encoding="utf-8", newline="") as f:
                f.write(t)
        check(check_lossless(later, plan2, main2, d, moved2, status) == [], "later version lossless")
        # a document with nothing to move and no index is left alone
        quiet = "# T\n\n## Steps\n\nx\n"
        m3, s3, mv3 = apply_plan(make_plan(quiet), {})
        check(m3 == quiet and not s3 and not mv3, "nothing to move: unchanged")
    check(slugify("OPT3 t05 / t06: spike-list fixes before threading and a very long tail of words") == "opt3-t05-t06-spike-list-fixes-before-threading-and-a-very", "long slug")
    check(fixable('x docs/PHASE4.md "Worker-count check" y', mv) == ('docs/PHASE4.md "Worker-count check"', "docs/status/worker-count-check.md"), "fixable form")
    check(fixable('x docs/PHASE4.md "Other" y', mv) is None, "unknown title is not fixable")
    print("split_phase4 selftest:", "FAILED" if fails else "all passed")
    return 1 if fails else 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0], formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dry-run", action="store_true", help="write the result to a scratch dir (--out-dir), change nothing in the repository")
    ap.add_argument("--check", action="store_true", help="dry run + prove nothing is lost")
    ap.add_argument("--apply", action="store_true", help="write docs/PHASE4.md and docs/status/ in place, fix the fixable references")
    ap.add_argument("--selftest", action="store_true")
    ap.add_argument("--input", help="the PHASE4.md to split (default docs/PHASE4.md)")
    ap.add_argument("--status-dir", help="where the status files are read from / written (default: status/ beside the input)")
    ap.add_argument("--out-dir", help="dry run / check: where the result goes (default: a new temp dir)")
    ap.add_argument("--keep-name", action="append", help="one more section name that always stays (lower case prefix match)")
    ap.add_argument("--no-refs", action="store_true", help="skip the repository reference scan")
    ap.add_argument("--refs-out", help="also write the reference list to this file")
    args = ap.parse_args(argv)
    if args.selftest:
        return selftest()
    if not (args.dry_run or args.check or args.apply):
        ap.error("give --dry-run, --check or --apply")
    if args.apply and (args.dry_run or args.check):
        ap.error("--apply does not combine with --dry-run / --check (it checks itself)")
    return run(args)


if __name__ == "__main__":
    sys.exit(main())
